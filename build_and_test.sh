#!/bin/bash
# Build and test DuckDB-Swift integration

set -e

PROJECT_DIR="/Users/fl/Desktop/ParquetViewerSwift"
cd "$PROJECT_DIR"

echo "????????????????????????????????????????????????????????????????"
echo "?                                                              ?"
echo "?     ?? Building Parquet Viewer (Swift + DuckDB)             ?"
echo "?                                                              ?"
echo "????????????????????????????????????????????????????????????????"
echo ""

# Check if test file exists
TEST_FILE="/Users/fl/Python/Parquet_View/sample_data.parquet"
if [ ! -f "$TEST_FILE" ]; then
    echo "??  Warning: Test file not found at $TEST_FILE"
    echo "   Trying alternative locations..."
    
    ALT_FILE="/Users/fl/Python/Parquet_View/sample_products.parquet"
    if [ -f "$ALT_FILE" ]; then
        TEST_FILE="$ALT_FILE"
        echo "? Found: $TEST_FILE"
    else
        echo "? No Parquet test files found!"
        echo "   Please create one first."
        exit 1
    fi
fi

echo "?? Test file: $TEST_FILE"
FILE_SIZE=$(ls -lh "$TEST_FILE" | awk '{print $5}')
echo "?? File size: $FILE_SIZE"
echo ""

echo "????????????????????????????????????????????????????????????????"
echo "?  Step 1: Building project with DuckDB...                    ?"
echo "?  (This may take 2-3 minutes on first build)                 ?"
echo "????????????????????????????????????????????????????????????????"
echo ""

# Build the project
echo "? Running: swift build"
echo ""

if swift build 2>&1 | tee build.log; then
    echo ""
    echo "? Build successful!"
else
    echo ""
    echo "? Build failed!"
    echo "   Check build.log for details"
    exit 1
fi

echo ""
echo "????????????????????????????????????????????????????????????????"
echo "?  Step 2: Running SM-2 validation test                       ?"
echo "?  (Testing if DuckDB can read Parquet files)                 ?"
echo "????????????????????????????????????????????????????????????????"
echo ""

# Copy the test file to project
cp TestDuckDBReal.swift Sources/TestMain.swift 2>/dev/null || true

# Try to compile and run the test
echo "? Compiling test..."
if swiftc -I .build/debug -L .build/debug -lDuckDB TestDuckDBReal.swift -o test_duckdb 2>&1; then
    echo "? Test compiled"
    echo ""
    echo "?? Running test..."
    echo ""
    ./test_duckdb
else
    echo "??  Direct compilation failed, trying alternative method..."
    echo ""
    echo "Please run manually:"
    echo "  cd $PROJECT_DIR"
    echo "  swift -I .build/debug -L .build/debug TestDuckDBReal.swift"
fi

echo ""
echo "????????????????????????????????????????????????????????????????"
echo "?  Build and Test Complete!                                   ?"
echo "????????????????????????????????????????????????????????????????"
